import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.HashMap;
import java.util.Locale;

/*
 * This class dumps relevant information from java.util.Locale metadata as Go
 * source for the geodata package.
 */
class DumpLocale {
  private static final PrintWriter OUT =
      new PrintWriter(new OutputStreamWriter(System.out, StandardCharsets.UTF_8), true);

  private static String quote(String value) {
    StringBuilder result = new StringBuilder("\"");
    for (int offset = 0; offset < value.length(); ) {
      int codePoint = value.codePointAt(offset);
      offset += Character.charCount(codePoint);
      switch (codePoint) {
        case '"':
          result.append("\\\"");
          break;
        case '\\':
          result.append("\\\\");
          break;
        case '\b':
          result.append("\\b");
          break;
        case '\f':
          result.append("\\f");
          break;
        case '\n':
          result.append("\\n");
          break;
        case '\r':
          result.append("\\r");
          break;
        case '\t':
          result.append("\\t");
          break;
        default:
          if (codePoint < 0x20) {
            result.append(String.format("\\u%04x", codePoint));
          } else {
            result.appendCodePoint(codePoint);
          }
          break;
      }
    }
    return result.append('"').toString();
  }

  public static void main(String[] args) {
    OUT.println("// Code generated by tools/locale/DumpLocale.java; DO NOT EDIT.");
    OUT.println();
    OUT.println("package geodata");
    OUT.println();
    OUT.println("var LOCALE_DATA = map[string]map[string]string{");

    String[] countries = Locale.getISOCountries();
    String[] languages = Locale.getISOLanguages();
    Arrays.sort(countries);
    Arrays.sort(languages);

    // Name => first language code that maps to that name. Reusing the first
    // spelling saves about 30 percent in the generated source.
    HashMap<String, String> nameToLanguage = new HashMap<String, String>();
    for (String country : countries) {
      OUT.println("\t" + quote(country) + ": {");
      Locale countryLocale = new Locale("", country);
      for (String language : languages) {
        Locale languageLocale = new Locale(language);
        String displayCountry = countryLocale.getDisplayCountry(languageLocale);
        if (displayCountry == null || displayCountry.length() == 0) {
          continue;
        }
        String previousLanguage = nameToLanguage.get(displayCountry);
        String value;
        if (previousLanguage != null) {
          value = "*" + previousLanguage;
        } else {
          nameToLanguage.put(displayCountry, language);
          value = displayCountry;
        }
        OUT.println("\t\t" + quote(language) + ": " + quote(value) + ",");
      }
      OUT.println("\t},");
    }
    OUT.println("}");
    OUT.println();
    OUT.println("// LocaleData is the idiomatic Go spelling of LOCALE_DATA.");
    OUT.println("var LocaleData = LOCALE_DATA");
  }
}
